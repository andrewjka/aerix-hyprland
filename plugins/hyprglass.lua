-- ═══════════════════════════════════════════════════════════
-- HYPRGLASS — ПОЛНАЯ КОНФИГУРАЦИЯ
-- ═══════════════════════════════════════════════════════════

local hg = hl.plugin.hyprglass

hg.config({

    -- ═══════════════════════════════════════════
    -- 1. РАЗМЫТИЕ И ФАКТУРА СТЕКЛА
    -- ═══════════════════════════════════════════

    -- Сила размытия изображения за стеклом.
    -- Приблизительный масштаб радиуса: значение × 12 px.
    -- 0 = без размытия, 2 = сильное размытие.
    blur_strength = 0.65,

    -- Количество проходов Gaussian blur.
    -- Допустимые значения: 1–5.
    -- Больше проходов — выше нагрузка на GPU.
    blur_iterations = 3,

    -- Интенсивность зернистости матового стекла.
    -- 0 = без зерна, 1 = сильная зернистость.
    noise_strength = 0.02,

    -- Общая непрозрачность стеклянного эффекта.
    -- 0 = эффект невидим, 1 = полная интенсивность.
    glass_opacity = 1,


    -- ═══════════════════════════════════════════
    -- 2. ПРЕЛОМЛЕНИЕ И ЖИДКОЕ СТЕКЛО
    -- ═══════════════════════════════════════════

    -- Сила преломления изображения у краёв.
    -- 0 = нет искажений.
    -- 0.6 = приблизительно реалистичное стекло.
    refraction_strength = 0.8,

    -- Направление преломления.
    -- 0 = к центру поверхности.
    -- 1 = вдоль её краёв.
    -- Не влияет на режим линзы с edge_height > 0.
    refraction_flow = 0.0,

    -- Глубина распространения преломления.
    -- 0 = только узкая кромка, центр плоский.
    -- 1 = эффект распространяется глубже внутрь.
    -- Не влияет на режим линзы с edge_height > 0.
    refraction_spread = 1.0,

    -- Хроматическая аберрация.
    -- Разделение RGB-каналов у преломлённых краёв.
    -- 0 = без цветных полос.
    chromatic_aberration = 0.07,

    -- Увеличение изображения центральной выпуклостью.
    -- 0 = без увеличения, 1 = выраженная линза.
    -- Не применяется к contour layer surfaces.
    lens_distortion = 0.0,


    -- ═══════════════════════════════════════════
    -- 3. ГЕОМЕТРИЯ КРАЁВ
    -- ═══════════════════════════════════════════

    -- Относительная ширина оптической кромки.
    -- Доля от меньшего размера поверхности.
    -- Используется, когда edge_thickness_px = 0.
    edge_thickness = 0.06,

    -- Фиксированная ширина кромки
    -- в логических пикселях.
    -- При значении > 0 заменяет edge_thickness.
    edge_thickness_px = 18,

    -- Высота выпуклой линзы на краю стекла.
    -- 0 = мягкий край без выраженной линзы.
    -- Чем больше значение, тем сильнее изгиб.
    edge_height = 24,

    -- Отражение изображения окружающего фона
    -- внутри выпуклой кромки.
    -- 0 = без отражений, 1 = зеркальный эффект.
    -- Работает при edge_height > 0.
    fresnel_reflection = 0.32,


    -- ═══════════════════════════════════════════
    -- 4. ОСВЕЩЕНИЕ, БЛИКИ И ОБВОДКА
    -- ═══════════════════════════════════════════

    -- Интенсивность свечения по краям стекла.
    -- 0 = нет свечения, 1 = сильное свечение.
    fresnel_strength = 0.26,

    -- Наследование цвета фона свечением.
    -- 0 = собственный белый/заданный цвет.
    -- 1 = цвет изображения за стеклом.
    fresnel_tint = 0.35,

    -- Цвет краевого свечения в формате RRGGBBAA.
    -- Последние две цифры задают степень
    -- замещения белого выбранным цветом.
    fresnel_color = 0xffffff00,

    -- Интенсивность зеркального блика.
    -- 0 = без блика, 1 = сильный блик.
    specular_strength = 0.62,

    -- Направление источника зеркального блика.
    -- 0° = сверху, 90° = справа,
    -- 180° = снизу, 270° = слева.
    specular_angle = 315.0,

    -- Интенсивность тонкой световой линии
    -- вдоль границы стекла.
    -- 0 = без линии, 1 = выраженная линия.
    bevel_strength = 0.55,

    -- Ширина световой линии в логических пикселях.
    bevel_size = 1.5,

    -- Цвет световой линии (RRGGBBAA).
    -- Альфа определяет, насколько заданный цвет
    -- заменяет базовый белый.
    bevel_color = 0xffffff00,

    -- Наследование цвета фона световой линией.
    -- 0 = собственный цвет линии.
    -- 1 = цвета изображения за стеклом.
    bevel_tint = 0.40,

    -- Направление освещения кромки в градусах.
    -- 315° = источник света сверху слева.
    bevel_angle = 315.0,

    -- Затемнение части кромки,
    -- расположенной напротив источника света.
    -- 0 = нет затемнения, 1 = сильная тень.
    bevel_shadow = 0.18,


    -- ═══════════════════════════════════════════
    -- 5. ЦВЕТ И ОБРАБОТКА ИЗОБРАЖЕНИЯ
    -- ═══════════════════════════════════════════

    -- Оттенок стекла в формате 0xRRGGBBAA.
    -- Белый цвет, alpha 0x0C (~4.7%).
    -- 0xFFFFFF00 = отсутствие цветовой заливки.
    tint_color = 0xeaf2ff08,

    -- Множитель яркости изображения.
    -- 1.0 = исходная яркость.
    brightness = 1,

    -- Контраст изображения.
    -- 1.0 = исходный контраст.
    contrast = 0.94,

    -- Насыщенность изображения.
    -- 0 = чёрно-белое, 1 = исходные цвета.
    saturation = 1.2,

    -- Выборочное усиление насыщенности цветов.
    vibrancy = 0.30,

    -- Насколько vibrancy затрагивает тёмные области.
    -- 0 = действует везде.
    -- 1 = почти не влияет на чёрные участки.
    vibrancy_darkness = 0.65,

    -- Адаптивное затемнение ярких областей.
    -- 0 = выключено.
    adaptive_dim = 0.16,

    -- Адаптивное осветление тёмных областей.
    -- 0 = выключено.
    adaptive_boost = 0.00,


    -- ═══════════════════════════════════════════
    -- 6. ДОПОЛНИТЕЛЬНЫЕ ЭФФЕКТЫ ОКОН
    -- ═══════════════════════════════════════════

    -- Подмешивание содержимого самого окна
    -- к изображению за стеклом.
    -- 0 = выключено, 1 = максимальное смешивание.
    -- Работает только для обычных окон.
    self_sample = 0.0,

    -- Показывать за стеклом только wallpaper
    -- и нижние системные слои вместо других окон.
    -- 0 = обычный фон, 1 = режим X-ray.
    xray = 0,

    -- Подсветка стеклянной кромки активного окна.
    -- 0 = выключено, 1 = максимальная яркость.
    -- Не работает для layer surfaces.
    focus_light = 0.22,

    -- Цвет подсветки активного окна (RRGGBBAA).
    focus_light_color = 0xffffff00,

    -- Автоматическое усиление размытия,
    -- когда за стеклянным окном находятся другие окна.
    -- Над wallpaper стекло остаётся более прозрачным.
    -- 0 = выключено, 1 = полный эффект.
    -- Работает только для обычных окон.
    frost = 0.85,

    -- Дополнительное размытие для режима frost.
    -- Использует те же единицы, что blur_strength.
    -- Не влияет на результат при frost = 0.
    frost_blur = 2.0,


    -- ═══════════════════════════════════════════
    -- 7. ГЛОБАЛЬНЫЕ НАСТРОЙКИ ПЛАГИНА
    -- ═══════════════════════════════════════════

    -- Глобально включить HyprGlass.
    enabled = true,

    -- Базовая тема.
    -- Возможные значения: "dark", "light".
    default_theme = "light",

    -- Пресет по умолчанию.
    default_preset = "default",

    -- Автоматически отключать штатный blur Hyprland
    -- для окон, где применяется HyprGlass.
    -- Предотвращает конфликты двух эффектов.
    manage_window_blur = true,

    -- Пропускать полностью непрозрачные окна,
    -- если эффект всё равно не будет виден.
    -- Уменьшает нагрузку на GPU.
    skip_opaque_windows = true,

    -- Оптимизация многопроходного размытия.
    -- true = меньше проходов при том же результате.
    blur_fold = true,


    -- ═══════════════════════════════════════════
    -- 8. LAYER SURFACES
    -- QUICKSHELL / DOCK / PANEL / NOTIFICATIONS
    -- ═══════════════════════════════════════════

    layers = {

        -- Включить стекло для layer surfaces.
        enabled = true,

        -- Заменять штатный blur Hyprland
        -- эффектом HyprGlass на выбранных слоях.
        manage_blur = true,

        -- Общий пресет для всех слоёв.
        -- Пустая строка = использовать default_preset.
        preset = "",

        -- Способ определения стеклянной области:
        -- "auto"    = автоматически;
        -- "region"  = область, запрошенная приложением;
        -- "alpha"   = по видимым пикселям;
        -- "contour" = отдельные контуры объектов.
        mask_mode = "contour",

        -- Минимальный alpha-канал пикселя,
        -- при котором появляется стекло.
        -- Помогает исключать слабые тени.
        mask_threshold = 0.03,

        -- Плавность появления стекла
        -- на границах alpha-маски.
        -- 0 = жёсткая граница.
        mask_feather = 0.02,

        -- Пересчитывать стеклянный фон,
        -- когда изображение позади изменяется.
        -- false = отключить такие обновления.
        live_resample = true,

        -- Максимальная частота обновления фона.
        -- 0 = без ограничения.
        -- При live_resample = false не используется.
        live_resample_fps = 60,

        -- Экспериментальный режим:
        -- принудительно пересчитывать стекло
        -- каждый кадр независимо от изменений.
        -- Очень высокая потенциальная нагрузка.
        force_live_resample = false,
    },


    -- ═══════════════════════════════════════════
    -- 9. WAYLAND SUBSURFACES
    -- ═══════════════════════════════════════════

    subsurfaces = {

        -- Включить стекло для subsurfaces,
        -- которые запрашивают этот эффект.
        enabled = true,

        -- Пресет для всех таких элементов.
        preset = "default",

        -- Радиус скругления в логических пикселях.
        -- -1 = полностью округлая капсула.
        radius = -1,
    },


    -- ═══════════════════════════════════════════
    -- 10. КЕШИРОВАНИЕ ОБЫЧНЫХ ОКОН
    -- ═══════════════════════════════════════════

    windows = {

        -- Повторно использовать ранее вычисленный
        -- и размытый фон окна.
        -- Экономит GPU при статичном изображении.
        background_cache = true,

        -- Обновлять фон окна при изменениях
        -- содержимого позади него.
        live_resample = true,

        -- Максимальная частота обновления фона
        -- для обычных окон.
        -- 0 = без ограничения.
        live_resample_fps = 60,
    },


    -- ═══════════════════════════════════════════
    -- 11. ДИАГНОСТИКА И ПРОФИЛИРОВАНИЕ
    -- ═══════════════════════════════════════════

    debug = {

        -- Режим диагностики:
        -- "off"          = обычная работа;
        -- "hints_only"   = только render-pass hints;
        -- "gl_work_only" = GL-обработка без live-blur hints.
        -- Последние два режима нужны для профилирования.
        mode = "off",

        -- Измерять GPU-время стадий рендеринга.
        -- Результаты доступны через
        -- hyprctl hyprglass stats.
        timers = false,
    },
})


-- ═══════════════════════════════════════════════
-- 12. ПРАВИЛА ПРИМЕНЕНИЯ К СЛОЯМ
-- ═══════════════════════════════════════════════

-- Применять HyprGlass ко всем layer surfaces.
hg.layer("*")

-- Исключить поверхность обоев awww.
hg.layer("awww-daemon", {
    exclude = true,
})
